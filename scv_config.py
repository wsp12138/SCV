def stage_args(task: str, seed: int, run_dir: str | Path) -> list[Namespace]:
    """Return exact task/seed presets; only output locations are rebound.

    Use a fresh directory dedicated to this task and seed. In particular, a
    new LBF-4p3 run starts from scratch, without relying on the original
    machine's interrupted and subsequently resumed job.
    """
    if task not in TASK_SEEDS:
        raise ValueError(f"Unknown task {task!r}; choose from {', '.join(TASK_SEEDS)}")
    if seed not in TASK_SEEDS[task]:
        raise ValueError(f"No archived SCV preset for {task} seed {seed}; choose from {TASK_SEEDS[task]}")
    run = Path(run_dir).expanduser().resolve()
    stages = []
    previous_checkpoint = ""
    for name in _ORDER[task]:
        settings = {
            **_SHARED, **_TASK[task], **_STAGE.get((task, name), {}),
            **_SEED_OVERRIDES.get((task, name, seed), {}),
        }
        checkpoint = str(run / f"{name}.pt")
        stages.append(Namespace(
            **settings, seed=seed, output=str(run / f"{name}.json"),
            checkpoint_path=checkpoint, best_checkpoint_path=str(run / f"{name}.best.pt"),
            resume_checkpoint=previous_checkpoint,
        ))
        previous_checkpoint = checkpoint
    return stages
